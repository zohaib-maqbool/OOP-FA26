public class Marks {
    private int std1;
    private int std2;
    private int std3;

    public Marks() {
        this.std1 = 0;
        this.std2 = 0;
        this.std3 = 0;
    }

    public int getStd1() {
        return std1;
    }

    public void setStd1(int std1) {
        this.std1 = std1;
    }

    public int getStd2() {
        return std2;
    }

    public void setStd2(int std2) {
        this.std2 = std2;
    }

    public int getStd3() {
        return std3;
    }

    public void setStd3(int std3) {
        this.std3 = std3;
    }

}
